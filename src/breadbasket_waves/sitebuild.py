def inline(t: str) -> str:
    t = html.escape(t, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"\*([^*]+)\*", r"<em>\1</em>", t)
    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', t)


def image(alt: str, path: str) -> str:
    data = base64.b64encode((ROOT / path).read_bytes()).decode("ascii")
    return f'<figure><img alt="{html.escape(alt)}" src="data:image/png;base64,{data}"></figure>'


def md_to_html(md: str) -> str:
    out, para, items, rows = [], [], [], []

    def flush():
        nonlocal para, items, rows
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
        if items:
            out.append("<ul>" + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>")
        if rows:
            head, body = rows[0], rows[2:]
            out.append('<div class="scroll"><table><thead><tr>' + "".join(f"<th>{inline(c)}</th>" for c in head)
                       + "</tr></thead><tbody>" + "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r)
                                                          + "</tr>" for r in body) + "</tbody></table></div>")
        para, items, rows = [], [], []

    for line in md.splitlines():
        s = line.strip()
        if not s:
            flush()
        elif s.startswith("|"):
            if para or items:
                flush()
            rows.append([c.strip() for c in s.strip("|").split("|")])
        elif m := re.match(r"^!\[([^\]]*)\]\(([^)]+)\)$", s):
            flush()
            out.append(image(m.group(1), m.group(2)))
        elif m := re.match(r"^(#{1,3})\s+(.*)", s):
            flush()
            level = len(m.group(1)) + (1 if len(m.group(1)) == 1 else 0)
            out.append(f"<h{level}>{inline(m.group(2))}</h{level}>")
        elif m := re.match(r"^-\s+(.*)", s):
            if para:
                flush()
            items.append(m.group(1))
        elif items:
            items[-1] += " " + s
        else:
            para.append(s)
    flush()
    return "\n".join(out)


